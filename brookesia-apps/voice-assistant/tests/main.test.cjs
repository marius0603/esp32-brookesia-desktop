const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../src/app/main.js'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(__dirname,'../src/manifest.json'),'utf8'));
const screen=JSON.parse(fs.readFileSync(path.join(__dirname,'../src/res/screens/main.json'),'utf8'));
const declared=new Set(manifest.services.map(s=>s.name).concat(['SystemGui','SystemTimer']));
const views=new Map(),actions=[];
function indexViews(n,parent=''){const key=parent+'/'+n.id;views.set(key,n);for(const e of n.events||[])actions.push(e.action);for(const c of n.children||[])indexViews(c,key);}
indexViews(screen);
assert.equal(manifest.package.name.zh_CN,'小马助手');
assert.deepEqual(actions.sort(),['backend','talk']);
assert(!JSON.stringify(screen).includes('点击说话'));
assert(screen.children.reduce((n,c)=>n+c.placement.height,0)+(screen.children.length-1)*screen.layout.gap+2*screen.style.padding<=400);
let bindings=[],quiet=false,calls=[],texts={},values={},stored=null,state={state:'Idle',active:false,channel:false},book=true,volume=20;
const ctx=vm.createContext({brookesia:{start_service:n=>{assert.ok(declared.has(n),'Undeclared service: '+n);bindings.push(n);return n;},call_function(h,n,s){
 const a=JSON.parse(s);calls.push({h,n,a});let data=null;
 if(h==='SystemGui'&&a.Path)assert(views.has(a.Path),'Missing GUI view: '+a.Path);
 if(n==='GetVolume')data=volume;
 if(n==='GetState')data=h==='Audiobook'?{active:book}:h==='DeviceModes'?{do_not_disturb:quiet,resume_volume:70}:state;
 if(h==='Audiobook'&&n==='Stop')book=false;
 if(n==='Connect')state=h==='LocalVoice'?{state:'Ready',active:true,channel:true,message:'点击说话，再次点击发送'}:{state:'Activation',active:true,channel:false,activation_code:'123456',message:'请激活'};
 if(n==='FSReadText')data=stored;
 if(n==='FSWriteText')stored=a.Data;
 if(n==='Disconnect')state={state:'Idle',active:false,channel:false};
 if(n==='StartListening')state={state:'Listening',active:true,channel:true,level:50};
 if(n==='StopListening')state={state:'Thinking',active:true,channel:true};
 if(n==='SetText')texts[a.Path]=a.Text;
 if(n==='SetBinding'){const node=views.get(a.Path);assert(Object.values(node.bindings||{}).includes(a.Key),'Missing binding key: '+a.Key);values[a.Path+':'+a.Key]=a.Value;}
 if(n==='StartPeriodic')data=7;
 return JSON.stringify({success:true,data});
}}});
vm.runInContext(source,ctx);ctx.brookesia_app.on_start();
assert.equal(book,false);
assert.equal(calls.filter(c=>c.n==='Connect').at(-1).h,'LocalVoice');
assert.equal(texts['/main/header/state/status'],'就绪');
assert.equal(texts['/main/footer/backend/label'],'电脑模式');
assert.equal(texts['/main/conversation/welcome'],'你好，我是小马。');
assert.equal(values['/main/conversation/avatar:hidden'],'false');
assert.equal(values['/main/conversation/answer:hidden'],'true');
assert(!Object.values(texts).some(t=>t.includes('点击说话')));
assert.deepEqual(calls.filter(c=>c.n==='SubscribeAction').map(c=>c.a.Action),['talk','backend']);
ctx.brookesia_app.on_action('backend');
assert.equal(texts['/main/conversation/user'],'激活码 123456');
assert.equal(texts['/main/conversation/answer'],'xiaozhi.me');
ctx.brookesia_app.on_action('talk');
assert.equal(calls.filter(c=>c.n==='StartListening').length,0,'Activation must not record');
state={state:'Ready',active:true,channel:true};ctx.brookesia_app.on_timer();ctx.brookesia_app.on_action('talk');
assert.equal(state.state,'Listening');
assert.equal(values['/main/meter/fill:width'],'180');
assert.equal(texts['/main/controls/talk/label'],'发送');
ctx.brookesia_app.on_action('talk');assert.equal(state.state,'Thinking');
for(const stage of ['Starting','Uploading']){
 state={state:stage,active:true,channel:true};ctx.brookesia_app.on_timer();
 const before=calls.filter(c=>c.n==='StartListening').length;
 ctx.brookesia_app.on_action('talk');assert.equal(calls.filter(c=>c.n==='StartListening').length,before);
}
state={state:'Speaking',active:true,channel:true,user_text:'你好',answer:'你好，我是小马。'};ctx.brookesia_app.on_timer();
assert.equal(values['/main/conversation/avatar:hidden'],'true');
assert.equal(values['/main/conversation/answer:hidden'],'false');
assert.equal(texts['/main/conversation/user'],'你：你好');
ctx.brookesia_app.on_action('talk');assert.equal(state.state,'Listening','Main action can start the next turn during playback');
const countBefore=calls.length;
for(const action of ['connect','cancel','test','quieter','louder'])ctx.brookesia_app.on_action(action);
assert.equal(calls.length,countBefore,'Removed controls must not retain hidden actions');
assert.equal(calls.filter(c=>c.n==='SetVolume'||c.n==='TestMicrophone').length,0);
volume=65;ctx.brookesia_app.on_timer();assert.equal(texts['/main/footer/volume'],'音量 65%');
quiet=true;ctx.brookesia_app.on_timer();assert.equal(texts['/main/footer/volume'],'音量 70% · 静音');quiet=false;
state={state:'Error',active:false,channel:false,error:'电脑未连接'};ctx.brookesia_app.on_timer();
assert.equal(texts['/main/conversation/answer'],'电脑未连接');
assert.equal(texts['/main/controls/talk/label'],'连接');
ctx.brookesia_app.on_action('talk');assert.equal(state.state,'Activation');
state={state:'Ready',active:true,channel:true,stack_limit_hit:true,message:'请重新打开助手'};ctx.brookesia_app.on_timer();
assert.equal(texts['/main/header/state/status'],'异常');
assert.equal(texts['/main/conversation/answer'],'请重新打开助手');
const bindingCount=bindings.length;for(let n=0;n<120;n++)ctx.brookesia_app.on_timer();assert.equal(bindings.length,bindingCount);
ctx.brookesia_app.on_pause();assert.equal(state.active,false);
const count=calls.length;ctx.brookesia_app.on_timer();assert.equal(calls.length,count);
ctx.brookesia_app.on_resume();assert.equal(state.state,'Activation','Resume reconnects without a separate connect button');
ctx.brookesia_app.on_stop();assert.equal(state.active,false);
assert.equal(calls.filter(c=>c.n==='Stop'&&c.h==='SystemTimer').at(-1).a.TimerId,7);
vm.runInContext(source,ctx);ctx.brookesia_app.on_start();assert.equal(state.state,'Activation');
ctx.brookesia_app.on_action('backend');assert.equal(state.state,'Ready');
assert.equal(calls.filter(c=>c.n==='Connect').at(-1).h,'LocalVoice');
assert.deepEqual(fs.readFileSync(path.join(__dirname,'../src/res/images/launcher_icon.png')),fs.readFileSync(path.join(__dirname,'../../../themes/cartoon-q-v1/flash-fallback/assistant.png')));
console.log('Xiaoma assistant passed: new GUI paths, removed actions, activation gate, send, next turn, reconnect, hardware volume, pause/stop and Q icon');
