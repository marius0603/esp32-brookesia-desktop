"""Pixel-grid art for the extra aquarium residents and the stationary reef."""
from PIL import Image, ImageDraw

REEF_FISH = {"shark": (62, 28), "ray": (42, 28), "clown": (24, 18), "turtle": (36, 24)}


def fish_image(kind, phase):
    image = Image.new("RGBA", REEF_FISH[kind])
    p = ImageDraw.Draw(image)
    if kind == "shark":
        tail = phase * 3
        p.polygon([(19, 14), (7, 12), (1 + tail, 3), (3, 13), (6, 15),
                   (2, 23 - tail), (8, 21), (13, 17), (21, 19)], fill="#345371")
        p.polygon([(12, 14), (21, 10), (29, 8), (36, 1), (40, 1), (38, 8),
                   (49, 9), (56, 12), (61, 15), (58, 18), (49, 20), (38, 20),
                   (32, 26), (26, 27), (27, 20), (18, 18)], fill="#526B85")
        p.polygon([(15, 14), (28, 10), (37, 9), (49, 10), (57, 13), (59, 15),
                   (48, 14), (40, 16), (26, 16)], fill="#7C9DB4")
        p.polygon([(18, 17), (32, 17), (44, 15), (59, 15), (57, 18),
                   (48, 20), (36, 19), (31, 24), (32, 19)], fill="#CAD9DB")
        p.line([(45, 14), (43, 17)], fill="#36536B")
        p.line([(47, 14), (46, 17)], fill="#36536B")
        p.point((53, 13), fill="#19263C")
        p.point((53, 12), fill="#DAECED")
        p.line([(55, 17), (58, 17)], fill="#456174")
    elif kind == "ray":
        tips = (3, 23) if phase == 0 else (7, 26)
        p.line([(0, 16), (6, 17), (10, 16), (16, 14)], fill="#51789C", width=2)
        p.polygon([(13, 13), (21, 10), (26, tips[0]), (32, 6), (37, 10),
                   (41, 13), (38, 17), (30, 19), (23, tips[1]), (20, 21)],
                  fill="#567398")
        p.polygon([(15, 14), (24, 11), (27, tips[0] + 1), (33, 8), (38, 11),
                   (40, 14), (35, 16), (26, 16), (22, 21)], fill="#8FABC4")
        p.polygon([(16, 14), (26, 10), (34, 10), (38, 13), (35, 15), (24, 14)], fill="#ABCDD8")
        for dot in [(23, 13), (28, 14), (26, 16), (31, 12), (34, 14)]:
            p.point(dot, fill="#D9E4DF")
        p.point((36, 12), fill="#26334C")
    elif kind == "clown":
        tail = phase * 2
        p.polygon([(7, 8), (1, 4 + tail), (0, 6 + tail), (2, 10),
                   (0, 15 - tail), (2, 16 - tail), (8, 12)], fill="#693D46")
        p.polygon([(6, 8), (10, 4), (13, 1), (17, 2), (20, 5),
                   (23, 8), (23, 11), (21, 14), (16, 16), (13, 17),
                   (9, 15), (5, 12)], fill="#6F3840")
        p.polygon([(2, 7 + tail), (8, 9), (11, 5), (15, 3), (19, 5),
                   (22, 8), (22, 11), (19, 13), (15, 15), (11, 14),
                   (7, 12), (2, 14 - tail), (3, 10)], fill="#F28D3D")
        p.polygon([(17, 4), (19, 5), (16, 7), (16, 11), (18, 14),
                   (16, 15), (14, 12), (14, 8)], fill="#FFF0D1")
        p.polygon([(9, 6), (11, 5), (10, 9), (10, 12), (12, 14),
                   (10, 15), (8, 12), (8, 9)], fill="#F4E2C3")
        p.point((20, 8), fill="#291E31")
        p.point((19, 7), fill="#FFD18A")
    else:
        fin = phase * 4
        p.polygon([(12, 10), (4, 5 + fin), (2, 6 + fin), (7, 13), (12, 13)], fill="#42847D")
        p.polygon([(14, 14), (5, 18 + fin), (3, 20 + fin // 2), (9, 20), (17, 17)],
                  fill="#39736D")
        p.polygon([(23, 13), (29, 18 + fin), (27, 22), (23, 20), (19, 16)], fill="#559687")
        p.polygon([(25, 9), (29, 6), (33, 6), (35, 9), (34, 12), (31, 13),
                   (26, 13)], fill="#5AA992")
        p.polygon([(4, 11), (9, 6), (15, 4), (21, 5), (26, 8), (27, 12),
                   (24, 16), (18, 18), (10, 17), (5, 15)], fill="#345C59")
        p.polygon([(6, 11), (11, 7), (16, 5), (22, 6), (25, 9), (25, 12),
                   (21, 15), (15, 16), (9, 15)], fill="#66895B")
        p.polygon([(12, 9), (16, 7), (19, 8), (21, 11), (18, 14), (14, 13)],
                  fill="#B0BA74", outline="#456E5C")
        p.line([(8, 13), (11, 11), (12, 9), (11, 7)], fill="#476C57")
        p.line([(23, 7), (19, 8), (21, 11), (25, 11)], fill="#476C57")
        p.point((32, 8), fill="#142E38")
        p.point((31, 7), fill="#B4E1BE")
    return image


def with_coral(backdrop, night):
    pen = ImageDraw.Draw(backdrop)
    stone = ["#28415B", "#496086"] if night else ["#2A4B5A", "#527987"]
    rose = ["#633C62", "#B26886", "#F89EAD"] if night else ["#7C3E64", "#CF6C89", "#FFB29D"]
    violet = ["#413557", "#765789"] if night else ["#4F4469", "#A477B1"]
    pen.polygon([(63, 146), (68, 139), (79, 134), (95, 136), (108, 141), (113, 149),
                 (104, 152), (76, 152)], fill=stone[0])
    pen.polygon([(69, 141), (79, 135), (91, 136), (100, 138), (94, 141),
                 (81, 143)], fill=stone[1])
    branches = [
        [(83, 145), (81, 138), (81, 131), (78, 123), (78, 119)],
        [(81, 134), (74, 130), (73, 126), (70, 123)],
        [(81, 135), (87, 128), (87, 122), (91, 117)],
        [(86, 130), (93, 128), (96, 123)],
        [(78, 124), (73, 121), (73, 117)],
        [(91, 145), (97, 139), (97, 134), (100, 130), (100, 127)],
        [(97, 139), (104, 137), (107, 133)],
    ]
    for points in branches:
        pen.line(points, fill=rose[0], width=4)
        pen.line(points, fill=rose[1], width=2)
        pen.point(points[-1], fill=rose[2])
    for x, y in [(71, 143), (75, 146), (96, 146), (104, 143), (108, 145)]:
        pen.rounded_rectangle((x, y - 5, x + 3, y + 1), radius=2, fill=violet[0])
        pen.point((x + 1, y - 4), fill=violet[1])
    return backdrop
